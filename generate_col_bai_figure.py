"""
Generate Figure 14 — Cost-of-Living Adjusted Benefit Adequacy.

Three-panel chart:
  Panel A: BAI vs COL-BAI side-by-side (housing-only vs full cost-of-living adjusted)
  Panel B: MIT Living Wage Gap — weekly dollar deficit below survival floor
  Panel C: Historical trend — BAI, COL-BAI, and Living Wage Coverage across 2010/2018/2026

Three-tier fallback:
  1. data/col_bai_results.json (generated by col_bai_engine.py)
  2. Hardcoded engine defaults (col_bai_engine.compute_col_bai on CSV data)
  3. Fully hardcoded values embedded below

Run: python generate_col_bai_figure.py
"""
